/**
 * Wraps the Horoskopos engine as an ES module, for the two places that cannot
 * load it as a page script: the Worker (share previews, worker/horoskopos.ts)
 * and the tests (tests/horoskopos-share/).
 *
 * The engine ships as plain scripts in public/machines/natal/ that hang
 * themselves on `self`. Here both files are set, unchanged, inside one
 * function whose `self` is a private object and whose `document`, `window`
 * and module loaders are undefined, so the engine starts in its headless
 * mode and touches no globals. Nothing is evaluated at run time: the output
 * is ordinary source, written to worker/gen/ (not committed).
 *
 * Runs at the start of every `astro dev` and `astro build`
 * (src/integrations/horoskopos-engine.ts), and by `npm test`.
 */
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
export const ENGINE_MODULE = resolve(root, 'worker/gen/horoskopos-engine.js');

export function buildEngineModule() {
  const read = (f) => readFileSync(resolve(root, 'public/machines/natal', f), 'utf8');
  const out = `/* GENERATED by scripts/horoskopos-engine-module.mjs from public/machines/natal/. Do not edit. */
const g = {};
(function (self, window, document, global, module, exports, define, require, Path2D) {
${read('astronomy.min.js')}
;
${read('engine.js')}
}).call(g, g, undefined, undefined, undefined, undefined, undefined, undefined, undefined, class { constructor(d) { this.d = d; } });
export const natal = g.__natal;
export default natal;
`;
  mkdirSync(dirname(ENGINE_MODULE), { recursive: true });
  writeFileSync(ENGINE_MODULE, out);
  return ENGINE_MODULE;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) console.log('wrote', buildEngineModule());
